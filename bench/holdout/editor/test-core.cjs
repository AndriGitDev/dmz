const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({TextEncoder});
vm.runInContext(fs.readFileSync(__dirname+'/core.js','utf8'),context);
const C = vm.runInContext('ReviewCore',context);
const text = '🙂 Ása A\u0301sa';
assert.equal(C.boundary(text,3),5);
assert.equal(C.boundary(text,6),9);
assert.equal(C.utf16(text,5),3);
assert.throws(()=>C.boundary(text,1),/Unicode/);
for(const offset of [1,2,3,6,999,-1,true]) assert.throws(()=>C.utf16(text,offset));
const span={start:5,end:9,kind:'Person'};
assert.equal(C.entities([span],text,[])[0].end,9);
assert.throws(()=>C.entities([span,span],text,[]),/overlap/);
assert.throws(()=>C.entities([{...span,kind:'TenantTerm'}],text,[]),/configured/);
assert.equal(C.entities([{...span,kind:'TenantTerm'}],text,['Ása'])[0].kind,'TenantTerm');
const item={id:'excerpt-0001',text_sha256:'synthetic-hash',text};
const blank={id:item.id,text_sha256:item.text_sha256,entities:null,reviewed:false,extraction_verified:false,exclusion_reason:null,reviewer:null,issues:[]};
assert.throws(()=>C.formRow(blank,item,[],true),/Explicit/);
assert.throws(()=>C.formRow({...blank,reviewed:true,reviewer:'a',entities:[]},item,[],true),/extraction/);
const negative={...blank,reviewed:true,reviewer:'a',entities:[],extraction_verified:true};
assert.equal(C.formRow(negative,item,[],true).entities.length,0);
const excluded={...blank,reviewed:true,reviewer:'a',exclusion_reason:'Unreadable extraction'};
assert.equal(C.formRow(excluded,item,[],true).entities,null);
assert.throws(()=>C.formRow({...excluded,entities:[]},item,[],true),/excluded/);
const packet={packet_sha256:'packet',slot:'a',items:[item],terms:[]};
const progress={schema:1,packet_sha256:'packet',slot:'a',reviewer:'a',rows:[blank],draft_exclusions:['Unfinished note']};
assert.equal(C.progress(progress,packet).draft_exclusions[0],'Unfinished note');
for(const changed of [{...progress,slot:'b'},{...progress,packet_sha256:'other'},{...progress,rows:[]},{...progress,rows:[{...blank,text_sha256:'changed'}]},{...progress,draft_exclusions:[1]}]) assert.throws(()=>C.progress(changed,packet));
console.log('Offline review UTF-8 boundaries, overlap, explicit negatives/exclusions and progress identity checks passed');
